#!/usr/bin/env python3
"""Turn a downloaded 3D room mesh into a ready-to-map Gazebo world.

Usage (inside the container):
    python3 scripts/add_room.py <mesh_file> <room_name> [--scale S] [--z Z]

What it does:
  1. copies the mesh into src/smartphone_robot/meshes/<room_name>/
  2. writes src/smartphone_robot/worlds/<room_name>.world referencing it
     (both <visual> and <collision>, so the LiDAR actually sees the walls)
  3. prints the one command that maps it with RViz open.

The mesh is referenced by an absolute file:// path into the source tree, which is stable
on this machine (symlink-install). Supported mesh types: .dae .obj .stl .

Scale/up-axis caveats: downloaded meshes vary. If the robot sees walls far too close or
far, re-run with --scale (e.g. 0.001 if the mesh is in millimetres). If the room looks
tipped over, the mesh uses a Y-up convention; re-export it Z-up or tell me and I add a
rotation.
"""

import argparse
import pathlib
import shutil
import sys

PKG = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'smartphone_robot'
CONTAINER_SRC = '/home/dev/ros2_ws/src/smartphone_robot'   # path Gazebo sees


def _ensure_obj_normals(path):
    """Add simple per-face normals to an OBJ that lacks them (prevents a DART crash)."""
    import math
    lines = path.read_text().splitlines()
    if any(l.startswith('vn ') for l in lines):
        return  # already has normals
    verts = []
    for l in lines:
        if l.startswith('v '):
            _, x, y, z = l.split()[:4]
            verts.append((float(x), float(y), float(z)))
    out, normals, face_n = [], [], {}

    def face_idx(tok):
        return int(tok.split('/')[0]) - 1

    # first pass: compute one normal per face, collect them
    for l in lines:
        if l.startswith('f '):
            idx = [face_idx(t) for t in l.split()[1:]]
            a, b, c = verts[idx[0]], verts[idx[1]], verts[idx[2]]
            u = (b[0]-a[0], b[1]-a[1], b[2]-a[2])
            v = (c[0]-a[0], c[1]-a[1], c[2]-a[2])
            n = (u[1]*v[2]-u[2]*v[1], u[2]*v[0]-u[0]*v[2], u[0]*v[1]-u[1]*v[0])
            m = math.sqrt(sum(k*k for k in n)) or 1.0
            n = (n[0]/m, n[1]/m, n[2]/m)
            normals.append(n)
            face_n[l] = len(normals)  # 1-based vn index

    for l in lines:
        out.append(l)
        if l.startswith('v ') and not any(x.startswith('vn ') for x in out[-3:]):
            pass
    # rebuild: keep v lines, append all vn after them, rewrite f lines with //vn
    vlines = [l for l in lines if l.startswith('v ')]
    other_head = [l for l in lines if not l.startswith(('v ', 'f ', 'vn '))]
    flines = [l for l in lines if l.startswith('f ')]
    body = other_head + vlines
    body += [f'vn {n[0]:.4f} {n[1]:.4f} {n[2]:.4f}' for n in normals]
    for i, l in enumerate(flines):
        vn = i + 1
        toks = l.split()[1:]
        body.append('f ' + ' '.join(f'{face_idx(t)+1}//{vn}' for t in toks))
    path.write_text('\n'.join(body) + '\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mesh')
    ap.add_argument('name')
    ap.add_argument('--scale', type=float, default=1.0)
    ap.add_argument('--z', type=float, default=0.0, help='lift the mesh in metres')
    ap.add_argument('--spawn', default='0 0', help='robot spawn "x y" in metres (default room centre)')
    a = ap.parse_args()

    mesh = pathlib.Path(a.mesh).expanduser()
    if not mesh.exists():
        sys.exit(f'Mesh not found: {mesh}')
    if mesh.suffix.lower() not in ('.dae', '.obj', '.stl'):
        sys.exit(f'Unsupported mesh type {mesh.suffix}; use .dae .obj .stl')

    name = a.name.strip().replace(' ', '_')
    mesh_dir = PKG / 'meshes' / name
    mesh_dir.mkdir(parents=True, exist_ok=True)
    dest = mesh_dir / mesh.name
    shutil.copy(mesh, dest)
    # DART's mesh collision segfaults on an OBJ without vertex normals. Downloaded .dae
    # and .stl meshes carry normals; a bare .obj may not, so add per-face normals if the
    # file has none. (Only .obj is handled here; .dae/.stl are assumed to have them.)
    if dest.suffix.lower() == '.obj':
        _ensure_obj_normals(dest)
    # also copy sibling textures/mtl if present (obj/dae need them)
    for sib in mesh.parent.iterdir():
        if sib.is_file() and sib.suffix.lower() in ('.mtl', '.png', '.jpg', '.jpeg', '.tga'):
            shutil.copy(sib, mesh_dir / sib.name)

    uri = f'file://{CONTAINER_SRC}/meshes/{name}/{mesh.name}'
    world = f'''<?xml version="1.0" ?>
<!--
  Auto-generated by scripts/add_room.py from a user-supplied 3D mesh.
  The robot maps this room with its 2D LiDAR: the laser slices the 3D mesh at its own
  height and SLAM builds a 2D floor plan. The mesh is both the visual and the collision,
  so the laser hits it.
-->
<sdf version="1.10">
  <world name="{name}">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <gravity>0 0 -9.8</gravity>
    <scene>
      <ambient>0.7 0.7 0.7 1</ambient>
      <background>0.6 0.7 0.85 1</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 12 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <direction>-0.4 0.3 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>60 60</size></plane></geometry>
          <material><ambient>0.4 0.4 0.42 1</ambient><diffuse>0.5 0.5 0.52 1</diffuse></material></visual>
      </link>
    </model>
    <model name="{name}_mesh">
      <static>true</static>
      <pose>0 0 {a.z} 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><mesh><uri>{uri}</uri><scale>{a.scale} {a.scale} {a.scale}</scale></mesh></geometry>
        </collision>
        <visual name="visual">
          <geometry><mesh><uri>{uri}</uri><scale>{a.scale} {a.scale} {a.scale}</scale></mesh></geometry>
        </visual>
      </link>
    </model>
  </world>
</sdf>
'''
    world_path = PKG / 'worlds' / f'{name}.world'
    world_path.write_text(world)

    print(f'Mesh  -> {dest}')
    print(f'World -> {world_path}')
    print()
    print('Rebuild, then run:')
    print('  cd ~/ros2_ws && colcon build --symlink-install')
    sx, sy = (a.spawn.split() + ['0', '0'])[:2]
    print(f'  ros2 launch smartphone_robot mapping.launch.py world:={name}.world \\')
    print(f'    x:={sx} y:={sy} rviz:=true')
    print()
    print('If the robot spawns inside a wall or sees nothing, change x/y to an open spot.')


if __name__ == '__main__':
    main()
